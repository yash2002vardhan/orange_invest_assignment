"""Fixtures plus generation of the eval table (reports/eval_table.md) from the test run itself."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from harness import TEST_SECRET, Harness

ROOT = Path(__file__).resolve().parent.parent
RESULTS: dict[str, dict] = {}


@pytest.fixture(autouse=True)
def _fake_secret(monkeypatch):
    monkeypatch.setenv("OPENAI_API_KEY", TEST_SECRET)
    monkeypatch.delenv("OPENROUTER_API_KEY", raising=False)
    monkeypatch.delenv("JEV_API_KEY", raising=False)
    monkeypatch.delenv("TYPESAFE_API_KEY", raising=False)


@pytest.fixture
def make_harness(tmp_path, request):
    made: list[Harness] = []

    def factory(**kwargs) -> Harness:
        h = Harness(tmp_path, **kwargs)
        made.append(h)
        request.node._harness = h
        return h

    yield factory
    for h in made:
        h.check_invariants()


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    marker = item.get_closest_marker("eval")
    if marker is None:
        return
    row = RESULTS.setdefault(item.nodeid, {
        "scenario": marker.kwargs["scenario"], "expected": marker.kwargs["expected"],
        "passed": True, "actual": "", "notes": ""})
    if rep.failed:
        row["passed"] = False
        msg = rep.longreprtext.strip().splitlines()
        row["notes"] = ("FAILED in " + rep.when + ": " + (msg[-1] if msg else ""))[:200]
    h = getattr(item, "_harness", None)
    if h is not None:
        row["actual"] = h.actual or row["actual"]
        if row["passed"]:
            row["notes"] = h.notes


def _cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def pytest_sessionfinish(session, exitstatus):
    if not RESULTS:
        return
    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    rows = list(RESULTS.values())
    passed = sum(r["passed"] for r in rows)
    lines = [
        "# Eval results",
        "",
        f"Generated by `pytest` from the scripted-user scenarios in `tests/test_evals.py`. "
        f"**{passed}/{len(rows)} passed.** Every scenario also runs the invariant checker in "
        "`tests/harness.py` (no mutation without a granted approval from a literal 'yes', fingerprint match, "
        "no success claim without `get_booking_status`, no duplicate bookings, no secrets in the trace).",
        "",
        "| # | Scenario | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | {_cell(r['scenario'])} | {_cell(r['expected'])} | {_cell(r['actual'])} | "
                     f"{'PASS' if r['passed'] else 'FAIL'} | {_cell(r['notes'])} |")
    (out / "eval_table.md").write_text("\n".join(lines) + "\n")
    (out / "eval_results.json").write_text(json.dumps(rows, indent=2))
